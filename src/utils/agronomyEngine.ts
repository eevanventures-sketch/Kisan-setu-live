export interface AgronomyResult {
  reply: string;
  expertName: string;
  designation: string;
  matchedTopic: string;
}

function normalizeHindiAgriQuery(raw: string): string {
  return (raw || '')
    .toLowerCase()
    .trim()
    .replace(/कल\s*रतवा/g, 'काला रतुआ')
    .replace(/रतवा/g, 'रतुआ')
    .replace(/गेहु\b/g, 'गेहूं')
    .replace(/गेहूँ/g, 'गेहूं')
    .replace(/माहु/g, 'माहू')
    .replace(/सरसो\b/g, 'सरसों')
    .replace(/पिलापन/g, 'पीलापन')
    .replace(/इल्लि|सुंडी|सुण्डी/g, 'इल्ली')
    .replace(/जलेबि/g, 'जलेबी')
    .replace(/सफैद/g, 'सफेद')
    .replace(/झोंका/g, 'झोंका')
    .replace(/ब्लास्ट/g, 'ब्लास्ट')
    .replace(/उकता|उकटा|उखटा|उगटा/g, 'उकठा')
    .replace(/चने/g, 'चना')
    .replace(
      /हरबसाइड|हर्बिसाइड|हरबीसाइड|हर्बीसाइड|हर्बिसइड|हरबिसाइड|अरबसाइड|हार्वीसाइड|वीडिसाइड|खरपतवार\s*नाशक|खरपतवार\s*नाशी|निंदा\s*नाशक|चारा\s*मार|घास\s*मार|weedicide/g,
      'खरपतवार हरबसाइड'
    )
    .replace(/फंजीसाइड|फन्जीसाइड|फंगिसाइड|फंगीसाइड|फफूंद\s*नाशक|फफूंदी\s*की\s*दवा/g, 'फफूंदनाशक')
    .replace(/पेस्टिसाइड|पेस्टीसाइड|कीट\s*नाशक|इंसेक्टिसाइड/g, 'कीटनाशक')
    .replace(/कल्ले|फुटाव|टिलरिंग|ब्यात/g, 'कल्ले फुटाव')
    .replace(/यूरिआ|युरिया/g, 'यूरिया')
    .replace(/सिचाई|सिचाईं|सीचाई|पाणी/g, 'सिंचाई पानी')
    .replace(/लहसून|लसन|लहशन/g, 'लहसुन')
    .replace(/सोयाबिन|सोयाविन/g, 'सोयाबीन')
    .replace(/मसुर/g, 'मसूर')
    .replace(/कंडवा|गिरवी/g, 'कंडुआ');
}

